CREATE TABLE "ENVIRONMENT"(
    "ID" UUID NOT NULL PRIMARY KEY,
    "LABEL" CHARACTER VARYING(160) NOT NULL UNIQUE,
    "NAMESPACE" CHARACTER VARYING(120),
    "KUBECONFIG_PATH" CHARACTER VARYING(500),
    "CREATED_AT" TIMESTAMP NOT NULL,
    "UPDATED_AT" TIMESTAMP NOT NULL
);
CREATE TABLE "PROJECT"(
    "ID" UUID NOT NULL PRIMARY KEY,
    "NAME" CHARACTER VARYING(120) NOT NULL UNIQUE,
    "STATUS" CHARACTER VARYING(20) NOT NULL,
    "DESCRIPTION" CHARACTER VARYING(100000),
    "CREATED_AT" TIMESTAMP NOT NULL,
    "UPDATED_AT" TIMESTAMP NOT NULL
);
CREATE TABLE "TASK"(
    "ID" UUID NOT NULL PRIMARY KEY,
    "NAME" CHARACTER VARYING(160) NOT NULL,
    "STATUS" CHARACTER VARYING(20) NOT NULL,
    "DESCRIPTION" CHARACTER VARYING(100000),
    "PROJECT_ID" UUID NOT NULL REFERENCES "PROJECT"("ID") ON DELETE CASCADE,
    "ENVIRONMENT_ID" UUID REFERENCES "ENVIRONMENT"("ID"),
    "CREATED_AT" TIMESTAMP NOT NULL,
    "UPDATED_AT" TIMESTAMP NOT NULL,
    UNIQUE ("PROJECT_ID", "NAME")
);
CREATE TABLE "DOCUMENT"(
    "ID" UUID NOT NULL PRIMARY KEY,
    "TITLE" CHARACTER VARYING(255) NOT NULL,
    "KIND" CHARACTER VARYING(40) NOT NULL,
    "BODY_MARKDOWN" CHARACTER VARYING(100000) NOT NULL,
    "SOURCE_PATH" CHARACTER VARYING(500),
    "POSITION" INTEGER NOT NULL,
    "PROJECT_ID" UUID REFERENCES "PROJECT"("ID") ON DELETE CASCADE,
    "TASK_ID" UUID REFERENCES "TASK"("ID") ON DELETE CASCADE,
    "ENVIRONMENT_ID" UUID REFERENCES "ENVIRONMENT"("ID") ON DELETE CASCADE,
    "CREATED_AT" TIMESTAMP NOT NULL,
    "UPDATED_AT" TIMESTAMP NOT NULL
);

