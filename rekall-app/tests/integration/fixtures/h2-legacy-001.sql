-- A Rekall H2 database as the first release left it: only the four 001 changesets applied.
-- Projects and tasks had names, not labels; notes hung off exactly one project, task or
-- environment. Written by hand from 001-core.yaml, as Liquibase would have built it on H2.
CREATE TABLE "DATABASECHANGELOG"(
    "ID" CHARACTER VARYING(255) NOT NULL,
    "AUTHOR" CHARACTER VARYING(255) NOT NULL,
    "FILENAME" CHARACTER VARYING(255) NOT NULL,
    "DATEEXECUTED" TIMESTAMP NOT NULL,
    "ORDEREXECUTED" INTEGER NOT NULL,
    "EXECTYPE" CHARACTER VARYING(10) NOT NULL
);
