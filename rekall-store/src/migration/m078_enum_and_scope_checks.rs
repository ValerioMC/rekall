//! `078`: the schema refuses what only the Rust enums refused before. An enum-like text column
//! holds one of its stored names, and a document is scoped to a company or a project, never both.
//! SQLite adds a constraint only by rebuilding the table, so each affected table is created again
//! with the same columns, keys and indexes, its rows copied over; a row that breaks a new rule makes
//! the migration fail, naming nothing it would rewrite.

