import type { TaskId } from '@/model/branded'
import type { TokenDay } from '@/features/tokens/model/token-usage'

export type TrendRange = '30d' | '90d' | 'all'

export interface TrendRangeOption {
  readonly id: TrendRange
  readonly label: string
  /** How many days the range ends with, or null for everything. */
  readonly days: number | null
}

export const TREND_RANGES: readonly TrendRangeOption[] = [
  { id: '30d', label: '1 month', days: 30 },
  { id: '90d', label: '3 months', days: 90 },
  { id: 'all', label: 'All', days: null }
]

/** One calendar day of a trend: what it generated that day and the running total. */
export interface TrendPoint {
  readonly day: string
  readonly generated: number
  readonly cumulative: number
}

const DAY_MS = 86_400_000

function dayNumber(day: string): number {
  return Math.floor(Date.parse(`${day}T00:00:00Z`) / DAY_MS)
}

function dayName(number: number): string {
  return new Date(number * DAY_MS).toISOString().slice(0, 10)
}

/** Today as a UTC `YYYY-MM-DD`, the way the server cuts its days. */
export function utcToday(now: Date = new Date()): string {
  return now.toISOString().slice(0, 10)
}

/**
 * The tokens generated by `taskIds` as a running total, one point per calendar day so a quiet day
 * is a flat stretch, ending today. The range starts at least a day before the last point, so work
 * on one day only still draws a line, and never earlier than the first day of work.
 */
export function trendOf(
  days: readonly TokenDay[],
  taskIds: ReadonlySet<TaskId>,
  range: TrendRange,
  today: string
): TrendPoint[] {
  const generatedOn = new Map<number, number>()
  for (const entry of days) {
    if (!taskIds.has(entry.taskId)) continue
    const key = dayNumber(entry.day)
    generatedOn.set(key, (generatedOn.get(key) ?? 0) + entry.outputTokens)
  }
  if (generatedOn.size === 0) return []

  const keys = [...generatedOn.keys()]
  const last = Math.max(dayNumber(today), ...keys)
  const span = TREND_RANGES.find((option) => option.id === range)?.days ?? null
  const earliest = Math.min(...keys) - 1
  const start = span === null ? earliest : Math.max(earliest, last - (span - 1))

  let cumulative = 0
  for (const [key, generated] of generatedOn) if (key < start) cumulative += generated

  const points: TrendPoint[] = []
  for (let key = Math.min(start, last - 1); key <= last; key++) {
    const generated = generatedOn.get(key) ?? 0
    cumulative += generated
    points.push({ day: dayName(key), generated, cumulative })
  }
  return points
}

/** One task's trend. */
export function taskTrend(
  days: readonly TokenDay[],
  taskId: TaskId,
  range: TrendRange,
  today: string
): TrendPoint[] {
  return trendOf(days, new Set([taskId]), range, today)
}

/** The smallest 1, 2 or 5 times a power of ten that holds the value: a scale top that reads. */
export function niceCeiling(value: number): number {
  if (value <= 0) return 1
  const magnitude = 10 ** Math.floor(Math.log10(value))
  const scaled = value / magnitude
  const step = scaled <= 1 ? 1 : scaled <= 2 ? 2 : scaled <= 5 ? 5 : 10
  return step * magnitude
}

export interface ChartBox {
  readonly width: number
  readonly height: number
  readonly top: number
  readonly right: number
  readonly bottom: number
  readonly left: number
}

export interface ChartGeometry {
  readonly xs: readonly number[]
  readonly ys: readonly number[]
  readonly line: string
  readonly area: string
}

/** The line and the filled area under it for values scaled from 0 to `ceiling` inside the box. */
export function chartGeometry(values: readonly number[], ceiling: number, box: ChartBox): ChartGeometry {
  const innerWidth = box.width - box.left - box.right
  const innerHeight = box.height - box.top - box.bottom
  const floor = box.top + innerHeight
  const xs = values.map(
    (_, index) => box.left + (values.length > 1 ? (index / (values.length - 1)) * innerWidth : innerWidth)
  )
  const ys = values.map((value) => floor - (Math.min(value, ceiling) / ceiling) * innerHeight)
  if (values.length === 0) return { xs, ys, line: '', area: '' }
  const line = xs
    .map((x, index) => `${index === 0 ? 'M' : 'L'}${x.toFixed(1)} ${ys[index]!.toFixed(1)}`)
    .join(' ')
  const area = `${line} L${xs[xs.length - 1]!.toFixed(1)} ${floor.toFixed(1)} L${xs[0]!.toFixed(1)} ${floor.toFixed(1)} Z`
  return { xs, ys, line, area }
}

/** `Oct 12`, from a `YYYY-MM-DD`, in the UTC day the server cut it at. */
export function shortDay(day: string): string {
  return new Date(`${day}T00:00:00Z`).toLocaleDateString('en-US', {
    month: 'short',
    day: 'numeric',
    timeZone: 'UTC'
  })
}
