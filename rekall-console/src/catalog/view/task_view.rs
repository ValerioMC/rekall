use rekall_kernel::{Id, Instant};
use rekall_store::{TaskKind, TaskStatus, TaskStepState};

use crate::catalog::TaskGraph;

#[derive(Clone, Debug)]
pub struct TaskView {
    pub id: Id,
    pub label: String,
    pub title: String,
    pub status: TaskStatus,
    pub description: Option<String>,
    pub project_id: Id,
    pub project_label: String,
    pub project_title: String,
    pub company_name: String,
    pub project_repo_folder: Option<String>,
    pub document_count: usize,
    pub step_count: usize,
    pub steps_done: usize,
    pub draft_step_count: usize,
    pub has_wrapup: bool,
    pub review_state: TaskStepState,
    pub review_active: bool,
    pub claimed_at: Option<Instant>,
    pub accepted_at: Option<Instant>,
    pub tag_id: Option<Id>,
    pub tag_name: Option<String>,
    pub tag_icon: Option<String>,
    pub tag_color: Option<String>,
    pub graph_laid_at: Option<Instant>,
    pub release_skipped: bool,
    pub kind: TaskKind,
    pub epic_id: Option<Id>,
    pub quick: bool,
    pub auto_accepted: bool,
    pub depends_on: Vec<Id>,
    pub tracker_issue_key: Option<String>,
    pub tracker_issue_url: Option<String>,
    pub tracker_sync_error: Option<String>,
    pub pull_request_number: Option<i64>,
    pub pull_request_url: Option<String>,
    pub pull_request_failure: Option<String>,
    pub pull_request_merged_at: Option<Instant>,
    pub anchor: String,
    pub updated_at: Instant,
}

impl TaskView {
    pub fn of(graph: &TaskGraph<'_>) -> Self {
        let task = graph.task;
        let project = graph.project;
        Self {
            id: task.id,
            label: task.label.clone(),
            title: task.title.clone(),
            status: task.status,
            description: task.description.clone(),
            project_id: project.id,
            project_label: project.label.clone(),
            project_title: project.title.clone(),
            company_name: graph.company.name.clone(),
            project_repo_folder: project.repo_folder.clone(),
            document_count: graph.document_count,
            step_count: graph.steps.iter().filter(|s| !s.state.draft()).count(),
            steps_done: graph.steps.iter().filter(|s| s.is_done()).count(),
            draft_step_count: graph.steps.iter().filter(|s| s.state.draft()).count(),
            has_wrapup: graph.has_wrapup,
            review_state: task.review_state,
            review_active: rekall_store::task::review_active(graph.steps.iter().map(|s| &s.state)),
            claimed_at: task.claimed_at,
            accepted_at: task.accepted_at,
            tag_id: graph.tag.map(|t| t.id),
            tag_name: graph.tag.map(|t| t.name.clone()),
            tag_icon: graph.tag.map(|t| t.icon.clone()),
            tag_color: graph.tag.map(|t| t.color.clone()),
            graph_laid_at: task.graph_laid_at,
            release_skipped: task.release_skipped,
            kind: task.kind,
            epic_id: task.epic_id,
            quick: task.quick,
            auto_accepted: task.auto_accepted,
            depends_on: graph.depends_on.clone(),
            tracker_issue_key: graph.tracker_link.and_then(|link| link.issue_key.clone()),
            tracker_issue_url: graph.tracker_link.and_then(|link| link.issue_url.clone()),
            tracker_sync_error: graph.tracker_link.and_then(|link| link.sync_error.clone()),
            pull_request_number: graph.pull_request.and_then(|pull_request| pull_request.number),
            pull_request_url: graph.pull_request.and_then(|pull_request| pull_request.url.clone()),
            pull_request_failure: graph.pull_request.and_then(|pull_request| pull_request.failure.clone()),
            pull_request_merged_at: graph.pull_request.and_then(|pull_request| pull_request.merged_at),
            anchor: task.anchor(&project.label),
            updated_at: task.updated_at,
        }
    }
}
